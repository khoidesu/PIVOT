"""Sự kiện idempotent + áp dụng tác động nghiệp vụ (DRAFT 4.1).

- Unique (source_system, source_event_id): gửi lại → trả bản ghi cũ, KHÔNG tạo tác động thứ hai.
- ingest chỉ lưu sự kiện gốc + ghi outbox job trong CÙNG transaction; worker mới áp dụng tác động (consumer idempotent).
- Tin đến muộn / sai thứ tự không kéo trạng thái lùi (vd TRIP_STARTED sau completed → quality_status='late').
- ETA đổi: đề xuất CHƯA cam kết → hết hiệu lực để tính lại; chuyến ĐÃ cam kết → chỉ tạo ngoại lệ xin quyết định,
  không tự sửa/chuyển xe.
"""
import uuid
from datetime import datetime, timedelta

from sqlalchemy import func, select
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from .. import models as m
from ..auth import Actor
from ..benefits import service as benefits
from ..booking import service as bk
from . import payloads

SUPPORTED = {"TRIP_STARTED", "TRIP_COMPLETED", "ETA_UPDATED", "VEHICLE_POSITION", "VEHICLE_AVAILABLE",
             "INCIDENT_REPORTED", "CARGO_DAMAGE_REPORTED", "GATE_CHECK_IN", "UNLOAD_STARTED", "UNLOAD_COMPLETED"}
TRIP_EVENTS = {"TRIP_STARTED", "TRIP_COMPLETED", "ETA_UPDATED", "INCIDENT_REPORTED", "GATE_CHECK_IN"}
NODE_EVENTS = {"UNLOAD_STARTED", "UNLOAD_COMPLETED"}  # chỉ ICD (node) của slot được báo   # chỉ nhà vận tải sở hữu xe được báo
VEHICLE_EVENTS = {"VEHICLE_POSITION", "VEHICLE_AVAILABLE"}        # chỉ nhà vận tải sở hữu xe được báo
SYSTEM_EVENTS = {"MILESTONE_REACHED"}                      # chỉ hệ thống sinh ra, không nhận từ ngoài
FINAL_QUALITY = {"applied", "late", "invalid"}
CLOCK_TOLERANCE = timedelta(minutes=15)  # lệch đồng hồ máy khách tới mức này vẫn coi vị trí là "vừa nhận"


def _authorize(session: Session, actor: Actor, entity_type: str, entity_id, event_type: str):
    """Trả (entity). Nguồn dữ liệu gốc phải đúng chủ thể: số đo/vị trí/ETA chỉ do nhà vận tải sở hữu xe báo."""
    if entity_type == "vehicle":
        veh = session.get(m.Vehicle, entity_id)
        if veh is None or veh.tenant_id != actor.org_id or actor.role != "carrier":
            raise bk.BookingError("NOT_FOUND", "Entity not found", 404)
        if event_type not in VEHICLE_EVENTS:
            raise bk.BookingError("VALIDATION", f"{event_type} is not a vehicle event", 422)
        return veh
    prop = session.get(m.Proposal, entity_id)
    if prop is None:
        raise bk.BookingError("NOT_FOUND", "Entity not found", 404)
    ship, veh = session.get(m.Shipment, prop.shipment_id), session.get(m.Vehicle, prop.vehicle_id)
    slot = session.get(m.Slot, prop.slot_id) if prop.slot_id else None
    if actor.org_id not in bk.party_orgs(ship, veh, slot).values():  # không phải bên liên quan → không biết là có tồn tại
        raise bk.BookingError("NOT_FOUND", "Entity not found", 404)
    if event_type in VEHICLE_EVENTS:
        raise bk.BookingError("VALIDATION", f"{event_type} must target a vehicle", 422)
    if event_type in TRIP_EVENTS and not (actor.role == "carrier" and actor.org_id == veh.tenant_id):
        raise bk.BookingError("FORBIDDEN", "Only the carrier that owns the vehicle can report trip events", 403)
    if event_type in NODE_EVENTS and not (actor.role == "node_operator" and slot is not None and slot.node_org_id == actor.org_id):
        raise bk.BookingError("FORBIDDEN", "Only the terminal operator of the slot can report unloading events", 403)
    return prop


def ingest(session: Session, actor: Actor, body: dict, now: datetime) -> tuple[m.Event, bool]:
    entity_type = body.get("entity_type", "proposal")
    if body["event_type"] in SYSTEM_EVENTS:
        raise bk.BookingError("VALIDATION", f"{body['event_type']} is generated by the system", 422)
    _authorize(session, actor, entity_type, body["entity_id"], body["event_type"])
    payload = payloads.validate(session, body["event_type"], body.get("payload") or {}, body["occurred_at"], now) \
        if body["event_type"] in SUPPORTED else (body.get("payload") or {})

    ev = m.Event(tenant_id=actor.org_id, entity_type=entity_type, entity_id=body["entity_id"], event_type=body["event_type"],
                 occurred_at=body["occurred_at"], received_at=now, source_system=body["source_system"],
                 source_event_id=body["source_event_id"], payload=payload,
                 correlation_id=body.get("correlation_id"),
                 quality_status="ok" if body["event_type"] in SUPPORTED else "unsupported")
    try:
        with session.begin_nested():
            session.add(ev)
            session.flush()
    except IntegrityError:
        existing = session.execute(select(m.Event).where(
            m.Event.source_system == body["source_system"],
            m.Event.source_event_id == body["source_event_id"])).scalar_one()
        if existing.tenant_id != actor.org_id:  # không lộ sự kiện của tổ chức khác
            raise bk.BookingError("CONFLICT", "source_event_id already used", 409) from None
        return existing, True
    if body["event_type"] in SUPPORTED:
        session.add(m.OutboxJob(topic="event.apply", payload={"event_id": str(ev.id)}, dedupe_key=f"apply:{ev.id}"))
    return ev, False


def _apply_vehicle_event(session: Session, ev: m.Event) -> str:
    veh = session.execute(select(m.Vehicle).where(m.Vehicle.id == ev.entity_id).with_for_update()).scalar_one()
    win = session.execute(select(m.AvailabilityWindow).where(m.AvailabilityWindow.vehicle_id == veh.id)
                          .order_by(m.AvailabilityWindow.free_from.desc()).with_for_update()).scalars().first()
    p = ev.payload or {}
    if ev.event_type == "VEHICLE_POSITION":
        last = session.execute(select(func.max(m.Event.occurred_at)).where(
            m.Event.entity_type == "vehicle", m.Event.entity_id == veh.id, m.Event.event_type == "VEHICLE_POSITION",
            m.Event.quality_status == "applied", m.Event.id != ev.id)).scalar_one()
        ref = last if last is not None else veh.position_updated_at  # chưa có tin nào → so với dữ liệu hiện có (seed)
        if ref is not None and ev.occurred_at <= ref:
            return "late"  # tin cũ hơn dữ liệu đang có: không kéo tuổi dữ liệu lùi
        # Tuổi dữ liệu đo bằng giờ MÁY CHỦ khi nhận: đồng hồ máy khách chậm/nhanh không làm vị trí vừa gửi thành "cũ".
        # Chỉ khi tin thực sự cũ (muộn hơn ngưỡng chịu lệch) mới tính theo giờ xảy ra.
        fresh = ev.received_at - ev.occurred_at <= CLOCK_TOLERANCE
        veh.position_updated_at = ev.received_at if fresh else ev.occurred_at
        if p.get("location_id") and win is not None:
            win.location_id = uuid.UUID(p["location_id"])
        if "lat" in p:
            veh.lat, veh.lng, veh.speed_kmh = p["lat"], p["lng"], p.get("speed_kmh")
            from ..tracking import service as tracking
            tracking.record_position(session, veh, ev)
        return "applied"
    # VEHICLE_AVAILABLE: bỏ qua nếu đã có tin khả dụng MỚI HƠN đã áp dụng
    newer = session.execute(select(m.Event.id).where(
        m.Event.entity_type == "vehicle", m.Event.entity_id == veh.id, m.Event.event_type == "VEHICLE_AVAILABLE",
        m.Event.quality_status == "applied", m.Event.occurred_at > ev.occurred_at)).first()
    if newer:
        return "late"
    loc, a, b = uuid.UUID(p["location_id"]), datetime.fromisoformat(p["free_from"]), datetime.fromisoformat(p["free_to"])
    if win is None:
        session.add(m.AvailabilityWindow(vehicle_id=veh.id, location_id=loc, free_from=a, free_to=b))
    else:
        win.location_id, win.free_from, win.free_to = loc, a, b
    if veh.status == "offline":  # nhà vận tải báo khả dụng → xe hỏng/ngoại tuyến được đưa lại vào ghép (xe `committed` thì giữ nguyên)
        veh.status = "available"
        veh.version += 1
    return "applied"


def _exception(session: Session, prop: m.Proposal, ev: m.Event, exc_type: str, detail: dict) -> None:
    """Mở ngoại lệ có phân mức + playbook + thông báo; idempotent theo sự kiện nguồn."""
    from ..incidents import service as incidents
    incidents.raise_exception(session, prop, exc_type, {**detail, "event_id": str(ev.id)}, ev.received_at, source="event",
                              dedupe_key=f"ev:{ev.id}")


def apply_event(session: Session, event_id: uuid.UUID, now: datetime) -> str:
    ev = session.get(m.Event, event_id)
    if ev is None or ev.quality_status in FINAL_QUALITY:
        return "skipped"  # đã xử lý rồi → không nhân đôi tác động
    if ev.entity_type == "vehicle":
        ev.quality_status = _apply_vehicle_event(session, ev)
        session.flush()
        return ev.quality_status
    prop = bk.lock_proposal(session, ev.entity_id)
    ship, veh, slot = bk.lock_resources(session, prop)
    status = prop.status

    if ev.event_type == "TRIP_STARTED":
        if status == "confirmed":
            prop.status, ev.quality_status = "executing", "applied"
            prop.version += 1
        else:  # đến muộn (đã executing/completed) hoặc chưa được xác nhận
            ev.quality_status = "late" if status in ("executing", "completed") else "invalid"

    elif ev.event_type == "TRIP_COMPLETED":
        if status == "executing":
            prop.status, ev.quality_status = "completed", "applied"
            prop.version += 1
            ship.status, veh.status = "completed", "available"
            for r in session.execute(select(m.Reservation).where(
                    m.Reservation.proposal_id == prop.id, m.Reservation.status == "committed")).scalars():
                r.status = "released"  # tài nguyên được trả sau khi hoàn tất
            benefits.record_completion(session, prop, ev, ship, veh)  # ghi sổ lợi ích cùng transaction
        else:
            ev.quality_status = "late" if status == "completed" else "invalid"

    elif ev.event_type == "ETA_UPDATED":
        delay = int((ev.payload or {}).get("delay_minutes", 0))
        if status in bk.OPEN_STATES:
            bk.release_holds(session, prop.id, "expired")
            prop.status = "expired"
            prop.version += 1
            _exception(session, prop, ev, "ETA_CHANGED", {"delay_minutes": delay, "action": "proposal_expired_recompute"})
            ev.quality_status = "applied"
        elif status in ("confirmed", "executing"):
            _exception(session, prop, ev, "ETA_CHANGED", {"delay_minutes": delay, "action": "needs_decision"})
            from ..docks import service as docks
            docks.on_eta_delay(session, prop, delay)  # đề xuất khung dock mới (ICD chấp nhận mới áp dụng)
            ev.quality_status = "applied"  # chỉ tạo ngoại lệ; KHÔNG sửa chuyến đã cam kết
        else:
            ev.quality_status = "late" if status == "completed" else "invalid"

    elif ev.event_type in ("GATE_CHECK_IN", "UNLOAD_STARTED", "UNLOAD_COMPLETED"):
        from ..docks import service as docks
        ev.quality_status = docks.apply_dock_event(session, prop, ev) if status in ("confirmed", "executing", "completed") else "invalid"

    elif ev.event_type in ("INCIDENT_REPORTED", "CARGO_DAMAGE_REPORTED"):
        p = ev.payload or {}
        if status in ("confirmed", "executing"):
            if ev.event_type == "INCIDENT_REPORTED":
                _exception(session, prop, ev, p["kind"], {"delay_minutes": p.get("delay_minutes", 0), "note": p.get("note"), "reported_by": "carrier"})
            else:
                _exception(session, prop, ev, "CARGO_DAMAGE", {"note": p.get("note")})
            ev.quality_status = "applied"
        else:
            ev.quality_status = "late" if status == "completed" else "invalid"
    session.flush()
    return ev.quality_status
