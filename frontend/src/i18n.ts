export const dictionaries: Record<Lang, Dict> = { vi, en }
export type TFn = (key: string, params?: Record<string, string | number>) => string

export function translate(lang: Lang, key: string, params?: Record<string, string | number>): string {
  const raw = dictionaries[lang][key] ?? dictionaries.vi[key] ?? key
  return params ? raw.replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? `{${k}}`)) : raw
}

/** Lý do hiển thị = template + dữ liệu thật của gate (không do LLM sinh). */
export function reasonText(item: GateItem, t: TFn, fmtTime: (iso: string) => string): string {
  const d = item.detail ?? {}
  const params: Record<string, string | number> = {}
  for (const [k, v] of Object.entries(d)) {
    if (Array.isArray(v)) params[k] = v.join(', ')
    else if (typeof v === 'string' && /^\d{4}-\d{2}-\d{2}T/.test(v)) params[k] = fmtTime(v)
    else if (typeof v === 'string' || typeof v === 'number') params[k] = v
  }
  params.gate = item.gate
  let key = `reason.${item.reason_code}`
  if (item.reason_code === 'DATA_STALE' && d.subject === 'shipment') key = 'reason.DATA_STALE.shipment'
  if (item.reason_code === 'VEHICLE_UNAVAILABLE' && d.reserved) key = 'reason.VEHICLE_UNAVAILABLE.reserved'
  if (d.redacted && `${key}.short` in dictionaries.vi) key = `${key}.short` // dữ liệu đội xe của tổ chức khác đã được che
  if (!(key in dictionaries.vi)) key = 'reason.unknown'
  return t(key, params)
}

interface Ctx { lang: Lang; setLang: (l: Lang) => void; t: TFn }
const I18nContext = createContext<Ctx>({ lang: 'vi', setLang: () => {}, t: (k) => k })

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try { return (localStorage.getItem('pivot.lang') as Lang) === 'en' ? 'en' : 'vi' } catch { return 'vi' }
  })
  const value = useMemo<Ctx>(() => ({
    lang,
    setLang: (l) => { setLangState(l); try { localStorage.setItem('pivot.lang', l) } catch { /* bỏ qua */ } },
    t: (key, params) => translate(lang, key, params),
  }), [lang])
  return createElement(I18nContext.Provider, { value }, children)
}

export const useI18n = () => useContext(I18nContext)
